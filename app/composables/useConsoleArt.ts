const FRAME_INTERVAL = 200;
const MAX_FRAMES_BEFORE_CLEAR = 30;
// écart fenêtre / viewport au-delà duquel on considère les devtools ouverts
const DEVTOOLS_THRESHOLD = 160;

export function useConsoleArt() {
  let frameIndex = 0;
  let frameCounter = 0;
  let isOpen = false;
  let animInterval: ReturnType<typeof setInterval> | undefined;
  let checkInterval: ReturnType<typeof setInterval> | undefined;

  const start = () => {
    if (animInterval) return;
    animInterval = setInterval(() => {
      if (frameCounter >= MAX_FRAMES_BEFORE_CLEAR) {
        console.clear();
        frameCounter = 0;
      }
      console.log(FRAMES[frameIndex]);
      frameIndex = (frameIndex + 1) % FRAMES.length;
      frameCounter++;
    }, FRAME_INTERVAL);
  };

  const stop = () => {
    if (!animInterval) return;
    clearInterval(animInterval);
    animInterval = undefined;
    console.clear();
  };

  const check = () => {
    const open =
      window.outerWidth - window.innerWidth > DEVTOOLS_THRESHOLD ||
      window.outerHeight - window.innerHeight > DEVTOOLS_THRESHOLD;
    if (open === isOpen) return;
    isOpen = open;
    if (open) start();
    else stop();
  };

  onMounted(() => {
    window.addEventListener("resize", check);
    checkInterval = setInterval(check, 500);
    check();
  });

  onBeforeUnmount(() => {
    stop();
    clearInterval(checkInterval);
    window.removeEventListener("resize", check);
  });
}
